// The shipped pool of flows as the web reads it (docs/architecture/flows.md
// FL2, FL6). The web has no DOT parser, so this module renders each shipped
// flow, parsed with its segments expanded, into a committed snapshot under
// packages/web/lib/line: what the pool lists (kind, stations in order, ends,
// the segments it uses) and the graph to draw. Prompts stay out; a station's
// words are read from its run or its repo. `shippedFlows.test.ts` fails when
// a template moves and the snapshot did not; regenerate with
//
//   bun packages/cli/scripts/gen-shipped-flows.ts
import { describeFlow } from "./flowPool";
import { parseWorkflowSource } from "./parser";
import { BUILTIN_WORKFLOW_TEMPLATES } from "./templates";

export const SHIPPED_FLOWS_SNAPSHOT_PATH = "packages/web/lib/line/shippedFlows.generated.ts";

const NODE_FIELDS = ["id", "label", "shape", "type", "backend", "agent", "segment", "segment_label", "segment_flow", "segment_entry", "segment_exit", "stop"] as const;

export function shippedFlowsSnapshot() {
  return Object.entries(BUILTIN_WORKFLOW_TEMPLATES).map(([slug, src]) => {
    const { where: _where, file: _file, errors: _errors, ...flow } = describeFlow(slug, src, "shipped", null);
    const graph = parseWorkflowSource(src);
    const nodes = [...graph.nodes.values()].map((n) => Object.fromEntries(NODE_FIELDS.filter((k) => n[k] !== undefined).map((k) => [k, n[k]])));
    const edges = graph.edges.map((e) => ({ from: e.from, to: e.to, ...(e.label ? { label: e.label } : {}), ...(e.condition ? { condition: e.condition } : {}) }));
    return { ...flow, name: graph.name, nodes, edges };
  });
}

export function renderShippedFlowsModule(): string {
  return [
    "// GENERATED by `bun packages/cli/scripts/gen-shipped-flows.ts` from the",
    "// shipped templates in packages/cli/src/workflow/templates. Do not edit:",
    "// packages/cli/src/workflow/shippedFlows.test.ts fails on drift.",
    'import type { ShippedFlow } from "./flowPool";',
    "",
    // One flow a line: small, and a template change shows as that flow's line in a diff.
    "export const SHIPPED_FLOWS: ShippedFlow[] = [",
    ...shippedFlowsSnapshot().map((f) => `  ${JSON.stringify(f)},`),
    "];",
    "",
  ].join("\n");
}
