// The shipped pool of flows as the web reads it (docs/architecture/flows.md
// FL2, FL6). The web has no DOT parser, so this module renders each shipped
// flow, parsed with its segments expanded, into two committed snapshots under
// packages/web/lib/line. The first is what the pool lists (kind, stations in
// order, ends, the segments it uses) and the graph to draw; every surface
// that names a flow loads it. The second is each station's words and settings
// (prompt, script, model, limits), read only when a person opens a station,
// so the web loads it on demand. `shippedFlows.test.ts` fails when a template
// moves and a snapshot did not; regenerate with
//
//   bun packages/cli/scripts/gen-shipped-flows.ts
import { describeFlow, joinsPool } from "./flowPool";
import { parseWorkflowSource } from "./parser";
import { BUILTIN_WORKFLOW_TEMPLATES } from "./templates";

export const SHIPPED_FLOWS_SNAPSHOT_PATH = "packages/web/lib/line/shippedFlows.generated.ts";

const NODE_FIELDS = ["id", "label", "shape", "type", "backend", "agent", "segment", "segment_label", "segment_flow", "segment_entry", "segment_exit", "slot", "segment_generated", "stop", "max_visits"] as const;

export function shippedFlowsSnapshot() {
  return Object.entries(BUILTIN_WORKFLOW_TEMPLATES).filter(([slug, src]) => joinsPool(slug, src)).map(([slug, src]) => {
    const { where: _where, file: _file, errors: _errors, draft: _draft, ...flow } = describeFlow(slug, src, "shipped", null);
    const graph = parseWorkflowSource(src);
    const nodes = [...graph.nodes.values()].map((n) => Object.fromEntries(NODE_FIELDS.filter((k) => n[k] !== undefined).map((k) => [k, n[k]])));
    const edges = graph.edges.map((e) => ({ from: e.from, to: e.to, ...(e.label ? { label: e.label } : {}), ...(e.condition ? { condition: e.condition } : {}) }));
    return { ...flow, name: graph.name, nodes, edges };
  });
}

export const SHIPPED_FLOW_STATIONS_SNAPSHOT_PATH = "packages/web/lib/line/shippedFlowStations.generated.ts";

/** A station's words, stored once in `texts` and named by index: the change line repeats every segment's prompts. */
const STATION_TEXT_FIELDS = ["prompt", "script", "system", "doc"] as const;
const STATION_SETTING_FIELDS = ["model", "reasoning_effort", "backend", "agent", "definition", "isolated", "reviewer", "timeout", "max_visits", "max_retries", "parks", "output", "max_tokens"] as const;

export function shippedFlowStationsSnapshot(): { texts: string[]; flows: Record<string, Record<string, Record<string, string | number | boolean>>> } {
  const texts: string[] = [];
  const index = new Map<string, number>();
  const textId = (t: string) => {
    if (!index.has(t)) { index.set(t, texts.length); texts.push(t); }
    return index.get(t)!;
  };
  const flows: Record<string, Record<string, Record<string, string | number | boolean>>> = {};
  for (const [slug, src] of Object.entries(BUILTIN_WORKFLOW_TEMPLATES)) {
    if (!joinsPool(slug, src)) continue;
    const stations: Record<string, Record<string, string | number | boolean>> = {};
    for (const n of parseWorkflowSource(src).nodes.values()) {
      const out: Record<string, string | number | boolean> = {};
      for (const k of STATION_TEXT_FIELDS) if (typeof n[k] === "string" && n[k]) out[k] = textId(n[k]!);
      for (const k of STATION_SETTING_FIELDS) if (n[k] !== undefined && n[k] !== "") out[k] = n[k] as string | number | boolean;
      if (Object.keys(out).length) stations[n.id] = out;
    }
    flows[slug] = stations;
  }
  return { texts, flows };
}

export function renderShippedFlowStationsModule(): string {
  const { texts, flows } = shippedFlowStationsSnapshot();
  return [
    "// GENERATED by `bun packages/cli/scripts/gen-shipped-flows.ts` from the",
    "// shipped templates in packages/cli/src/workflow/templates. Do not edit:",
    "// packages/cli/src/workflow/shippedFlows.test.ts fails on drift.",
    "// Each station's words and settings, its texts named by index into TEXTS.",
    'import type { PackedStations } from "./flowStations";',
    "",
    "export const TEXTS: string[] = [",
    ...texts.map((t) => `  ${JSON.stringify(t)},`),
    "];",
    "",
    "export const STATIONS: Record<string, PackedStations> = {",
    ...Object.entries(flows).map(([slug, st]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(st)},`),
    "};",
    "",
  ].join("\n");
}

export function renderShippedFlowsModule(): string {
  return [
    "// GENERATED by `bun packages/cli/scripts/gen-shipped-flows.ts` from the",
    "// shipped templates in packages/cli/src/workflow/templates. Do not edit:",
    "// packages/cli/src/workflow/shippedFlows.test.ts fails on drift.",
    'import type { ShippedFlow } from "./flowPool";',
    "",
    // One flow a line: small, and a template change shows as that flow's line in a diff.
    "export const SHIPPED_FLOWS: ShippedFlow[] = [",
    ...shippedFlowsSnapshot().map((f) => `  ${JSON.stringify(f)},`),
    "];",
    "",
  ].join("\n");
}
