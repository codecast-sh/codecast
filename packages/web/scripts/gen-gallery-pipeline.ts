#!/usr/bin/env bun
// Writes lib/renderGalleryPipeline.generated.ts: what the real CLI prints for
// the pipeline's inline objects (docs/architecture/pipeline.md PL5, PL6), run
// in a scratch repository whose origin is example-org/example-app. Three
// edits in order (add lint after PR when landing/**, guidance on review,
// skip decide), then `cast flow pipeline` as text and as JSON. The render
// gallery and the edit card's tests both read it, so they follow the CLI
// when its output changes: rerun this after changing `cast flow edit` or
// `cast flow pipeline`.
//
//   bun packages/web/scripts/gen-gallery-pipeline.ts
import { spawnSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const CLI = join(import.meta.dir, "../../cli/src/index.ts");
const OUT = join(import.meta.dir, "../lib/renderGalleryPipeline.generated.ts");
const ansi = (s: string) => s.replace(/\x1b\[[0-9;]*m/g, "");

const dir = mkdtempSync(join(tmpdir(), "gallery-pipeline-"));
// An inherited GIT_DIR (under `git rebase --exec`, say) points every git below
// at the surrounding repository: `git init` there reinitialized it as bare.
const env: Record<string, string | undefined> = { ...process.env, NO_COLOR: "1", GIT_AUTHOR_DATE: "2026-01-01T00:00:00Z", GIT_COMMITTER_DATE: "2026-01-01T00:00:00Z" };
for (const k of ["GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_COMMON_DIR", "GIT_OBJECT_DIRECTORY"]) delete env[k];
const sh = (cmd: string, args: string[]) => {
  const r = spawnSync(cmd, args, { cwd: dir, encoding: "utf8", env });
  if (r.status !== 0) throw new Error(`${cmd} ${args.join(" ")} failed:\n${r.stderr}${r.stdout}`);
  return ansi(r.stdout).trimEnd();
};
const cast = (...args: string[]) => sh("bun", [CLI, ...args]);

try {
  sh("git", ["init", "-q"]);
  sh("git", ["remote", "add", "origin", "git@github.com:example-org/example-app.git"]);
  writeFileSync(join(dir, "README.md"), "Example app\n");
  sh("git", ["add", "."]);
  sh("git", ["-c", "user.name=Gallery", "-c", "user.email=gallery@example.com", "commit", "-qm", "init"]);
  const add = cast("flow", "edit", "change", "add", "lint", "--after", "pr", "--run", "bun run lint", "--when", "landing/**");
  const guide = cast("flow", "edit", "change", "guide", "review", "Also check the migrations");
  const skip = cast("flow", "edit", "change", "skip", "decide");
  const pipelineText = cast("flow", "pipeline");
  const pipelineJson = JSON.parse(cast("flow", "pipeline", "--json"));
  // No machine of ours in a committed fixture.
  delete pipelineJson.published;
  pipelineJson.device_id = null;
  pipelineJson.root = null;
  const src = `// Generated by scripts/gen-gallery-pipeline.ts from the real CLI in a scratch repository: do not edit by hand.
// What \`cast flow edit\` and \`cast flow pipeline\` print (pipeline.md PL5, PL6), for the render gallery and the edit card's tests.
import type { PipelinePublish } from "@codecast/shared/contracts/pipeline";

export const GALLERY_PIPELINE_REPO = "example-org/example-app";
export const EDIT_ADD = ${JSON.stringify({ command: `cast flow edit change add lint --after pr --run "bun run lint" --when "landing/**"`, output: add })};
export const EDIT_GUIDE = ${JSON.stringify({ command: `cast flow edit change guide review "Also check the migrations"`, output: guide })};
export const EDIT_SKIP = ${JSON.stringify({ command: "cast flow edit change skip decide", output: skip })};
export const PIPELINE_TEXT = ${JSON.stringify({ command: "cast flow pipeline", output: pipelineText })};
export const PIPELINE: PipelinePublish = ${JSON.stringify(pipelineJson)};
`;
  writeFileSync(OUT, src);
  console.log(`wrote ${OUT} (${src.length} bytes)`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
