// Writes lib/renderGalleryPersonal.generated.ts: the render gallery's personal Ship runs, each a moment of the real
// runner's recorded reports (lib/ship/__tests__/personalReports.json) as the server merges them (replayReports.ts),
// never hand-made. record-personal-reports.ts runs it after recording; run it alone after editing the moments:
//
//   bun packages/web/scripts/gen-personal-gallery-runs.ts
import * as fs from "node:fs";
import * as path from "node:path";
import { at, end, replay, type ReplayedRun } from "../lib/ship/__tests__/replayReports";

const RED = replay("a red check goes back to the session as one brief");
const PASS = replay("a passing check and a ship verdict land on origin's main");
const moments: Record<string, ReplayedRun> = {
  live: end(replay("a deploy with one step left for the person")),
  landed: end(replay("the rest end Deployed, unverified or Landed (run 4)")),
  unverified: end(replay("the rest end Deployed, unverified or Landed (run 1)")),
  round2: at(RED, { node: "review", status: "completed" }, 1),
  landing: at(PASS, { node: "land", status: "running" }),
  deploying: at(PASS, { node: "deploy", status: "running" }),
  red: at(RED, { node: "brief", status: "running" }),
  deployFix: at(replay("a failed deploy goes back to the session to fix the script"), { node: "deploy_fix", status: "running" }),
  unlanded: end(replay("a remote that refuses the push")),
  movingStop: end(replay("main that moves under Land four times in a row stops at Main keeps moving")),
};
// Times as offsets before the moment, so the gallery shows them as just now.
const last = (r: ReplayedRun) => Math.max(...r.node_statuses.map((n) => n.completed_at ?? n.started_at));
const shaped = Object.fromEntries(Object.entries(moments).map(([k, r]) => {
  const t = last(r);
  return [k, {
    status: r.status, current_node_id: r.current_node_id, ...(r.fail_reason ? { fail_reason: r.fail_reason } : {}), ...(r.merge ? { merge: r.merge } : {}),
    // The session it waits on is the gallery's own conversation; when it started waiting, the gallery's clock.
    ...(r.waiting_on_session ? { waiting_on_session: { node_id: r.waiting_on_session.node_id, note: r.waiting_on_session.note ?? "" } } : {}),
    node_statuses: r.node_statuses.map(({ session_id: _s, ...n }) => ({ ...n, started_at: n.started_at - t, ...(n.completed_at ? { completed_at: n.completed_at - t } : {}) })),
  }];
}));
const out = path.join(import.meta.dir, "..", "lib", "renderGalleryPersonal.generated.ts");
fs.writeFileSync(out, `// GENERATED by \`bun packages/web/scripts/gen-personal-gallery-runs.ts\` from the real runner's recorded reports
// (lib/ship/__tests__/personalReports.json). Do not edit. Times are milliseconds before the moment shown.
export const PERSONAL_GALLERY_RUNS = ${JSON.stringify(shaped, null, 1)} as const;
`);
console.log(`wrote ${out}`);
